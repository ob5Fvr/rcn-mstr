import ipaddress as _ip

_COMPILED = []
for _vendor, _nets in CDN_RANGES.items():
    for _n in _nets:
        try:
            _COMPILED.append((_ip.ip_network(_n), _vendor))
        except ValueError:
            pass
# sort by prefix length desc so the most specific match wins
_COMPILED.sort(key=lambda x: x[0].prefixlen, reverse=True)


def cdn_for_ip(ip: str):
    try:
        addr = _ip.ip_address(ip)
    except ValueError:
        return None
    for net, vendor in _COMPILED:
        if addr.version == net.version and addr in net:
            return vendor
    return None
