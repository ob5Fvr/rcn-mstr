@pytest.mark.asyncio
async def test_waf_bypass_via_header(fake_dns, tmp_path):
    """A fake origin that 403s /admin unless X-Forwarded-For: 127.0.0.1 is present."""
    async def conn(reader, writer):
        try:
            line = await asyncio.wait_for(reader.readline(), 3)
            parts = line.decode("latin-1").split()
            path = parts[1] if len(parts) > 1 else "/"
            headers = {}
            while True:
                h = await asyncio.wait_for(reader.readline(), 3)
                if h in (b"\r\n", b"\n", b""):
                    break
                k, _, v = h.decode("latin-1").partition(":")
                headers[k.strip().lower()] = v.strip()
            p = path.split("?")[0]
            if p.rstrip("/") == "/admin":
                if headers.get("x-forwarded-for") == "127.0.0.1":
                    body = b"<html><title>Admin Panel</title>welcome admin dashboard users settings</html>"
                    st = 200
                else:
                    body = b"<html><title>403 Forbidden</title>blocked by policy</html>"
                    st = 403
            else:
                body = b"<html><title>home</title></html>"
                st = 200
            out = f"HTTP/1.1 {st} X\r\ncontent-length: {len(body)}\r\nconnection: close\r\n\r\n".encode() + body
            writer.write(out)
            await writer.drain()
        except Exception:  # noqa
            pass
        finally:
            writer.close()
    srv = await asyncio.start_server(conn, "127.0.0.1", 0)
    port = srv.sockets[0].getsockname()[1]
    fake_dns.set("example.com", "A", ["127.0.0.1"])
    name = _seed(["example.com"])
    cfg = Config(domains=["example.com"], output=str(tmp_path / "o"),
                 modules=[name, "resolve", "probe", "waf"], resolvers=[fake_dns.resolver_str], tools=False,
                 brute=False, max_rounds=2, http_ports=[port], timeout=3.0)
    try:
        ctx = await run(cfg)
    finally:
        srv.close()
    bypass = [f for f in ctx.findings.values() if f["type"] == "waf_bypass"]
    assert bypass, "expected a waf_bypass finding"
    techniques = [b["technique"] for f in bypass for b in f["evidence"]["bypasses"]]
    assert any("x-forwarded-for" in t.lower() for t in techniques)
