"""WAF fingerprinting + bypass assessment."""
import asyncio

import pytest

from rcnmstr.context import Config
from rcnmstr.engine import run
from rcnmstr.base import Module
from rcnmstr.modules import waf


def _seed(hosts, name="wafseed"):
    class Seed(Module):
        pass
    Seed.name = name
    Seed.mode = "passive"
    Seed.phase = 5
    Seed.default = False

    async def _run(self, ctx):
        if ctx.round == 1:
            for h in hosts:
                ctx.add_host(h, "crtsh")
    Seed.run = _run
    return name


# --------------------------------------------------------------- detection unit tests
def test_detect_cloudflare():
    w = waf.detect_waf(403, {"cf-ray": "abc", "server": "cloudflare"}, [],
                       "Attention Required! | Cloudflare")
    assert any(x["vendor"] == "Cloudflare" for x in w)


def test_detect_akamai_and_f5():
    a = waf.detect_waf(403, {"server": "AkamaiGHost"}, [], "Reference #18.abcd")
    assert any(x["vendor"] == "Akamai" for x in a)
    f = waf.detect_waf(403, {}, ["TSxxxxxx=abc; Path=/"], "The requested URL was rejected. Your support ID is 123")
    assert any(x["vendor"] == "F5 BIG-IP ASM" for x in f)


def test_detect_incapsula_cookie():
    w = waf.detect_waf(200, {}, ["incap_ses_123=xyz"], "")
    assert any(x["vendor"] == "Imperva Incapsula" for x in w)


def test_detect_none_on_clean():
    assert waf.detect_waf(200, {"server": "nginx"}, [], "<html><title>hi</title></html>") == []


def test_generic_block_detection():
    assert waf.looks_blocked(403, "")
    assert waf.looks_blocked(200, "Your request has been blocked by our Web Application Firewall")
    assert not waf.looks_blocked(200, "<html><title>welcome</title>normal page</html>")


@pytest.mark.parametrize("vendor,status,headers,cookies,body", [
    ("Sucuri CloudProxy", 403, {"x-sucuri-id": "1"}, [], "Access Denied - Sucuri Website Firewall"),
    ("Wordfence", 503, {}, [], "Generated by Wordfence"),
    ("PerimeterX / HUMAN", 403, {}, ["_pxhd=abc"], "Please verify you are a human"),
    ("Datadome", 403, {"x-datadome": "protected"}, ["datadome=xyz"], ""),
    ("Citrix NetScaler", 403, {}, ["ns_af=q"], "NetScaler"),
    ("AWS WAF / ELB", 403, {"x-amzn-waf-action": "block"}, [], ""),
])
def test_detect_various(vendor, status, headers, cookies, body):
    w = waf.detect_waf(status, headers, cookies, body)
    assert any(x["vendor"] == vendor for x in w), f"{vendor} not detected"


